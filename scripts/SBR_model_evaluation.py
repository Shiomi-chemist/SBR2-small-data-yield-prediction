"""Code S2. Matched-split ElasticNet evaluation of SBR representations.
 
Reads feature CSVs produced by Code S1. All models and null baselines
use the same 70:30 partitions (seeds 0-9). For each SBR representation,
ElasticNet hyperparameters are selected within the training set via
five-fold CV. Outputs individual-split and mean +/- SD metric tables.
"""
from pathlib import Path
import numpy as np
import pandas as pd
from sklearn.linear_model import ElasticNet
from sklearn.metrics import mean_absolute_error, r2_score
from sklearn.model_selection import KFold, ParameterGrid, cross_val_score, train_test_split
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
 
# Input files are generated by Code S1.
# Select the same reaction dataset used in Code S1.
# Run this script from the repository root directory.

# DATASET = "ML_redam"
# DATASET = "ML_deamino"
# DATASET = "ML_electro"
DATASET = "ML_UmAS"

INPUT_DIR = Path("SBR_features")
OUTPUT_DIR = Path("SBR_model_results")
MODELS = ("SBR-C2", "SBR-2", "SBR-2P", "SBR-3")
SEEDS = range(10)
TEST_SIZE = 0.30
N_FOLDS = 5
N_JOBS = -1  # Set to 1 on memory-constrained computers.
ALPHAS = np.arange(0.1, 1.0, 0.1)
L1_RATIOS = np.arange(0.1, 1.0, 0.1)
PARAMETERS = list(ParameterGrid({"alpha": ALPHAS, "l1_ratio": L1_RATIOS}))
CV = KFold(n_splits=N_FOLDS, shuffle=True, random_state=0)
 
 
def model_pipeline(alpha, l1_ratio):
    return Pipeline([
        ("scaler", StandardScaler(with_mean=False)),
        ("model", ElasticNet(
            alpha=alpha, l1_ratio=l1_ratio,
            max_iter=500000, tol=1e-3,
            selection="random", random_state=0,
        )),
    ])
 
 
def tune_and_fit(X_train, y_train):
    best_score, best_parameters = -np.inf, None
    for params in PARAMETERS:
        scores = cross_val_score(
            model_pipeline(**params), X_train, y_train,
            cv=CV, scoring="neg_mean_absolute_error", n_jobs=N_JOBS,
        )
        score = float(scores.mean())
        if score > best_score:
            best_score, best_parameters = score, params
    fitted = model_pipeline(**best_parameters)
    fitted.fit(X_train, y_train)
    return fitted, best_parameters, -best_score
 
 
def load_features():
    feature_matrices = {}
    reference = None
    for name in MODELS:
        path = INPUT_DIR / f"{DATASET}_{name}.csv"
        df = pd.read_csv(path)
        cols = [col for col in df if col.startswith("Morgan_")]
        expected = 4096 if name in ("SBR-C2", "SBR-2P") else 2048
        if len(cols) != expected:
            raise ValueError(f"{path}: expected {expected} features, found {len(cols)}")
        if df["num"].isna().any() or df["num"].duplicated().any():
            raise ValueError(f"{path}: missing/duplicated reaction identifiers")
        df = df.set_index("num", drop=False)
        if reference is None:
            reference = df
        else:
            if set(df.index) != set(reference.index):
                raise ValueError(f"{path}: inconsistent reaction identifiers")
            df = df.loc[reference.index]
            for col in ("reaction_id", "sm1", "sm2", "prod", "yield"):
                if not df[col].fillna("").equals(reference[col].fillna("")):
                    raise ValueError(f"{path}: inconsistent {col}")
        X = df[cols].to_numpy(dtype=float)
        if not np.isfinite(X).all():
            raise ValueError(f"{path}: non-finite fingerprint values")
        feature_matrices[name] = X
    y = pd.to_numeric(reference["yield"], errors="coerce").to_numpy(float)
    if not np.isfinite(y).all():
        raise ValueError("Missing/non-finite yields")
    return feature_matrices, y
 
 
def main():
    Xs, y = load_features()
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    records = []
    for seed in SEEDS:
        train_idx, test_idx = train_test_split(
            np.arange(len(y)), test_size=TEST_SIZE, random_state=seed,
        )
        y_train, y_test = y[train_idx], y[test_idx]
        for name, value in (("Null mean", y_train.mean()),
                            ("Null median", np.median(y_train))):
            pred = np.full(y_test.shape, value, dtype=float)
            records.append(dict(seed=seed, model=name,
                                MAE=mean_absolute_error(y_test, pred),
                                R2=r2_score(y_test, pred),
                                alpha=np.nan, l1_ratio=np.nan, CV_MAE=np.nan))
        for name, X in Xs.items():
            fitted, params, cv_mae = tune_and_fit(X[train_idx], y_train)
            pred = fitted.predict(X[test_idx])
            records.append(dict(seed=seed, model=name,
                                MAE=mean_absolute_error(y_test, pred),
                                R2=r2_score(y_test, pred),
                                alpha=params["alpha"],
                                l1_ratio=params["l1_ratio"], CV_MAE=cv_mae))
        print(f"Completed split {seed}")
 
    detail = pd.DataFrame(records)
    summary = (detail.groupby("model", as_index=False)
               .agg(mean_MAE=("MAE", "mean"), SD_MAE=("MAE", "std"),
                    mean_R2=("R2", "mean"), SD_R2=("R2", "std")))
    detail.to_csv(OUTPUT_DIR / f"{DATASET}_all_splits.csv", index=False)
    summary.to_csv(OUTPUT_DIR / f"{DATASET}_summary.csv", index=False)
    print(summary.round(3).to_string(index=False))
 
 
if __name__ == "__main__":
    main()
